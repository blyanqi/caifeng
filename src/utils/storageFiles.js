export async function downloadStorageFile(storage) {
  if (!storageSupportsFile(storage?.type)) {
    throw new Error(
      storageSupportsFolder(storage?.type)
        ? '文件夹类型请使用「打开文件夹」查看文件'
        : '数据库类型不支持文件下载',
    )
  }
  const query = new URLSearchParams({
    target: storage.target,
    type: storage.type,
  })
  let response
  try {
    response = await fetch(`/api/storage/download?${query.toString()}`)
  } catch {
    throw new Error('无法连接本地存储服务，请确认服务端正在运行')
  }
  if (!response.ok) {
    let message = '文件下载失败'
    try {
      const payload = await response.json()
      message = payload?.error || message
    } catch {
      // keep fallback message
    }
    throw new Error(message)
  }
  const blob = await response.blob()
  const filename = String(storage.target || '').split('/').pop() || `storage.${storage.type}`
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  document.body.appendChild(link)
  link.click()
  link.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
  return { filename, size: blob.size }
}
